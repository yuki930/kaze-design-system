#!/usr/bin/env node
/**
 * Builds tokens.css and src/tokens/generated.ts from the DTCG token files in
 * tokens/*.tokens.json, which are the single source of truth.
 *
 *   tokens/base.tokens.json       every token, light theme / warm palette / default density
 *   tokens/dark.tokens.json       overrides for [data-theme="dark"] (and the prefers-color-scheme fallback)
 *   tokens/<palette>.tokens.json       overrides for [data-palette="<palette>"]
 *   tokens/<palette>-dark.tokens.json  overrides for that palette + dark
 *     palettes: cool (霞), ink (墨), indigo (藍). The default warm palette (砂) is base.
 *   tokens/compact.tokens.json    overrides for [data-density="compact"]
 *
 * Each file groups tokens into three tiers: primitive (raw scales), semantic
 * (roles such as color-bg) and component (sizes for specific components).
 * A token's key is its CSS custom property name without the leading "--";
 * references use DTCG syntax: "{primitive.zinc-50}".
 *
 * `npm run tokens` writes the files; `npm run tokens -- --check` fails when
 * they are stale (used in CI).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TOKENS_DIR = path.join(root, "tokens");
const OUT_CSS = path.join(root, "tokens.css");
const OUT_TS = path.join(root, "src/tokens/generated.ts");
const TIERS = ["primitive", "semantic", "component"];
const check = process.argv.includes("--check");

const read = (name) =>
  JSON.parse(fs.readFileSync(path.join(TOKENS_DIR, `${name}.tokens.json`), "utf8"));
const base = read("base");
/** Palettes other than the default warm one, with the comment shown in tokens.css */
const PALETTES = [
  ["cool", "Cool palette 霞 (slate, purple-tinted gray)"],
  ["ink", "Ink palette 墨 (neutral gray, black primary)"],
  ["indigo", "Indigo palette 藍 (indigo-tinted gray, indigo primary and accent)"],
];
const modes = {
  dark: read("dark"),
  compact: read("compact"),
  ...Object.fromEntries(
    PALETTES.flatMap(([name]) => [
      [name, read(name)],
      [`${name}-dark`, read(`${name}-dark`)],
    ]),
  ),
};

/** Flattens a tier-grouped file into [name, token] pairs, primitive → semantic → component. */
function entries(file) {
  return TIERS.flatMap((tier) => Object.entries(file[tier] ?? {}));
}

const known = new Set(entries(base).map(([name]) => name));
for (const [mode, file] of Object.entries(modes)) {
  for (const [name] of entries(file)) {
    if (!known.has(name)) throw new Error(`${mode}.tokens.json overrides unknown token "${name}"`);
  }
}

/** "{semantic.color-fg}" → "var(--color-fg)" */
function toCss(value) {
  if (typeof value !== "string") throw new Error(`unsupported value ${JSON.stringify(value)}`);
  return value.replace(/^\{(primitive|semantic|component)\.([a-z0-9-]+)\}$/, (_, tier, name) => {
    if (!known.has(name)) throw new Error(`reference to unknown token "${tier}.${name}"`);
    return `var(--${name})`;
  });
}

function wrap(text, width = 72) {
  const lines = [];
  let line = "";
  for (const word of text.split(/\s+/)) {
    if (line && `${line} ${word}`.length > width) {
      lines.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) lines.push(line);
  return lines;
}

function comment(text, indent) {
  const [first, ...rest] = wrap(text);
  if (rest.length === 0) return `${indent}/* ${first} */`;
  return [`${indent}/* ${first}`, ...rest.map((l) => `${indent}   ${l}`)].join("\n").concat(" */");
}

function declarations(file, indent, { sections = false } = {}) {
  const out = [];
  let section = null;
  for (const [name, token] of entries(file)) {
    const meta = token.$extensions?.["jp.kaze"];
    if (sections && meta?.section && meta.section !== section) {
      section = meta.section;
      if (out.length) out.push("");
      out.push(`${indent}/* ── ${section} ${"─".repeat(Math.max(3, 52 - section.length))} */`);
      if (meta.sectionNote) out.push(comment(meta.sectionNote, indent));
    }
    const decl = `${indent}--${name}: ${toCss(token.$value)};`;
    const desc = token.$description;
    if (desc && desc.length <= 64 && !desc.includes("\n")) {
      out.push(`${decl} /* ${desc} */`);
    } else {
      if (desc) out.push(comment(desc, indent));
      out.push(decl);
    }
  }
  return out;
}

function block(selector, lines, indent = "") {
  return [`${indent}${selector} {`, ...lines, `${indent}}`].join("\n");
}

const css = [
  `/* GENERATED by scripts/build-tokens.mjs from tokens/*.tokens.json. Do not edit by hand:
   change the token files and run \`npm run tokens\`.

   Wrapped in @layer kaze.tokens so the file stays layered when imported on
   its own (e.g. \`import "kaze-design-system/css/tokens"\`). The \`kaze\` parent
   layer keeps these rules out of Tailwind's \`components\` / \`utilities\` layers.
   Unlayered author styles always win over these rules. */`,
  "@layer kaze.tokens {",
  block(":root", [
    ...declarations(base, "  ", { sections: true }),
    "",
    "  /* Proportional kana (palt) for all text. */",
    '  font-feature-settings: "palt" 1;',
    "",
    "  /* Breakpoints (reference only, use @media): sm 640px / md 768px /",
    "     lg 1024px / xl 1280px / 2xl 1536px */",
  ]),
  "",
  "/* Density: compact. Works on :root or any container; orthogonal to theme and palette. */",
  block('[data-density="compact"]', declarations(modes.compact, "  ")),
  "",
  "/* Dark theme */",
  block('[data-theme="dark"]', declarations(modes.dark, "  ")),
  "",
  ...PALETTES.flatMap(([name, label]) => [
    `/* ${label} */`,
    block(`[data-palette="${name}"]`, declarations(modes[name], "  ")),
    "",
    block(`[data-palette="${name}"][data-theme="dark"]`, declarations(modes[`${name}-dark`], "  ")),
    "",
  ]),
  `/* Dark fallback when no data-theme is set (JS disabled or before hydration).
   :root:not([data-theme="light"]) lets an explicit light choice win. */`,
  "@media (prefers-color-scheme: dark) {",
  block(':root:not([data-theme="light"])', declarations(modes.dark, "    "), "  "),
  "}",
  "",
  `/* Palette + dark fallbacks. Each needs its own selector: it has the same
   specificity as the warm fallback above and would otherwise lose to it. */`,
  "@media (prefers-color-scheme: dark) {",
  ...PALETTES.map(([name]) =>
    block(
      `:root[data-palette="${name}"]:not([data-theme="light"])`,
      declarations(modes[`${name}-dark`], "    "),
      "  ",
    ),
  ),
  "}",
  "}",
  "",
].join("\n");

const names = entries(base).map(([name]) => name);
const ts = `// GENERATED by scripts/build-tokens.mjs from tokens/*.tokens.json. Do not edit by hand.

/** Every CSS custom property defined by tokens.css, without the leading "--". */
export const tokenNames = [
${names.map((n) => `  "${n}",`).join("\n")}
] as const;

export type TokenName = (typeof tokenNames)[number];

/** \`cssVar("color-bg")\` → \`"var(--color-bg)"\`, type-checked against the token list. */
export function cssVar<Name extends TokenName>(name: Name): \`var(--\${Name})\` {
  return \`var(--\${name})\`;
}
`;

const outputs = [
  [OUT_CSS, css],
  [OUT_TS, ts],
];

if (check) {
  const stale = outputs.filter(([file, text]) => fs.readFileSync(file, "utf8") !== text);
  if (stale.length) {
    console.error(
      `[tokens] stale: ${stale.map(([f]) => path.relative(root, f)).join(", ")}. Run \`npm run tokens\`.`,
    );
    process.exit(1);
  }
  console.log("[tokens] up to date");
} else {
  for (const [file, text] of outputs) fs.writeFileSync(file, text);
  console.log(`[tokens] wrote tokens.css and src/tokens/generated.ts (${names.length} tokens)`);
}
